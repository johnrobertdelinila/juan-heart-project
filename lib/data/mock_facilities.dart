  /// Get facilities by type
  static List<Map<String, dynamic>> getFacilitiesByType(String type) {
    return getAllFacilities()
        .where((facility) => facility['type'] == type)
        .toList();
  }

  /// Get emergency facilities only
  static List<Map<String, dynamic>> getEmergencyFacilities() {
    return getAllFacilities()
        .where((facility) => facility['emergencyServices'] == true)
        .toList();
  }

  /// Get 24-hour facilities only
  static List<Map<String, dynamic>> get24HourFacilities() {
    return getAllFacilities()
        .where((facility) => facility['open24Hours'] == true)
        .toList();
  }

  /// Get facility count summary
  static Map<String, int> getFacilityCountSummary() {
    final all = getAllFacilities();
    return {
      'total': all.length,
      'hospitals': all.where((f) => f['type'] == 'Hospital').length,
      'clinics': all.where((f) => f['type'] == 'Clinic').length,
      'healthCenters': all.where((f) => f['type'] == 'Health Center').length,
      'emergency': all.where((f) => f['emergencyServices'] == true).length,
      'twentyFourHour': all.where((f) => f['open24Hours'] == true).length,
    };
  }
